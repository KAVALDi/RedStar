using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._RedStar.Beekeeping;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._RedStar.Beekeeping.UI;

/// <summary>
/// One hive's debug data, laid out like the plant analyzer: the hive with its sprite and colony on the left,
/// bees and nectar as bars and every known tray with its picture and state on the right. Tray colours match
/// the map overlay.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class BeeDebugWindow : FancyWindow
{
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    public BeeDebugWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Bees.AccentColor = Color.Gold;
        Nectar.AccentColor = Color.Orange;
        Health.AccentColor = Color.Crimson;
        Combs.AccentColor = Color.Khaki;
        Legend.SetMessage(FormattedMessage.FromMarkupOrThrow(Loc.GetString("beekeeping-debug-legend")));
    }

    public void SetHive(NetEntity hive)
    {
        if (_entityManager.TryGetEntity(hive, out var uid))
        {
            HiveSprite.SetEntity(uid.Value);
            HiveName.Text = $"{_entityManager.GetComponent<MetaDataComponent>(uid.Value).EntityName} ({hive})";
        }
        else
        {
            HiveName.Text = hive.ToString();
        }
    }

    public void ShowGone()
    {
        SourcesHeading.Text = Loc.GetString("beekeeping-debug-window-gone");
        Sources.RemoveAllChildren();
    }

    public void UpdateData(BeeHiveDebugData data)
    {
        Queen.Text = Loc.GetString(data.HasQueen ? "beekeeping-debug-yes" : "beekeeping-debug-no");
        Outside.Text = data.OutBees.ToString();
        Pause.Text = Loc.GetString($"beekeeping-debug-pause-{data.Pause.ToString().ToLowerInvariant()}");
        Scout.Text = data.Scout != null
            ? Loc.GetString("beekeeping-debug-scout-flying")
            : Loc.GetString($"beekeeping-debug-scout-{data.ScoutState.ToString().ToLowerInvariant()}");
        FoundLabel.Visible = Found.Visible = data.Scout != null;
        Found.Text = data.ScoutFound.Count.ToString();
        NextForager.Text = data.NextForagerTrip < 0f
            ? "-"
            : Loc.GetString("beekeeping-debug-seconds", ("s", (int) data.NextForagerTrip));
        NextTrip.Text = data.NextScoutTrip < 0f
            ? "-"
            : Loc.GetString("beekeeping-debug-seconds", ("s", (int) data.NextScoutTrip));
        Foragers.Text = data.Foragers.Count.ToString();

        Bees.Update(Loc.GetString("beekeeping-debug-bees"),
            $"{data.Bees} / {data.MaxBees}",
            progress: data.MaxBees > 0 ? (float) data.Bees / data.MaxBees : 0f);
        Nectar.Update(Loc.GetString("beekeeping-debug-nectar"),
            $"{data.Nectar:0.#} / {data.MaxNectar:0.#}",
            progress: data.MaxNectar > 0f ? data.Nectar / data.MaxNectar : 0f);

        Combs.Update(Loc.GetString("beekeeping-debug-combs"),
            $"{data.Combs} / {data.MaxCombs}",
            progress: data.MaxCombs > 0 ? (float) data.Combs / data.MaxCombs : 0f);

        Egg.Text = data.HasEgg
            ? Loc.GetString("beekeeping-debug-egg-there", ("s", (int) data.EggLeft))
            : data.EggCooldown > 0f
                ? Loc.GetString("beekeeping-debug-egg-cooldown", ("s", (int) data.EggCooldown))
                : data.EggFullFor > 0f
                    ? Loc.GetString("beekeeping-debug-egg-growing", ("s", (int) data.EggFullFor))
                    : Loc.GetString("beekeeping-debug-no");

        var queen = new FormattedMessage();
        if (data.Traits.Count == 0)
        {
            queen.AddText(Loc.GetString("beekeeping-debug-no-queen-traits"));
        }
        else
        {
            for (var i = 0; i < data.Traits.Count; i++)
            {
                if (i > 0)
                    queen.AddText(", ");

                if (_proto.Resolve(data.Traits[i], out var trait))
                {
                    queen.PushColor(trait.Color);
                    queen.AddText(Loc.GetString(trait.Name));
                    queen.Pop();
                }
                else
                {
                    queen.AddText(data.Traits[i].Id);
                }
            }
        }

        queen.PushNewline();
        queen.AddText(Loc.GetString("beekeeping-debug-queen-line", ("slots", data.Slots), ("payload", $"{data.Payload:0.#}")));
        QueenInfo.SetMessage(queen);

        Health.Update(Loc.GetString("beekeeping-debug-health"),
            $"{data.Health:0} / {data.MaxHealth:0}",
            progress: data.MaxHealth > 0f ? data.Health / data.MaxHealth : 0f);

        OutsideHeading.Text = Loc.GetString("beekeeping-debug-section-outside", ("count", data.Outside.Count));
        OutsideBees.RemoveAllChildren();
        if (data.Outside.Count == 0)
            OutsideBees.AddChild(new Label { Text = Loc.GetString("beekeeping-debug-outside-none") });
        foreach (var bee in data.Outside)
        {
            var kind = bee.Kind switch
            {
                BeeOutsideKind.Scout => "beekeeping-debug-outside-scout",
                BeeOutsideKind.Pollinator => "beekeeping-debug-outside-pollinator",
                _ => "beekeeping-debug-outside-lost",
            };
            OutsideBees.AddChild(new Label
            {
                Text = Loc.GetString("beekeeping-debug-outside-line",
                    ("name", Loc.GetString(kind)), ("s", Math.Max(0, (int) bee.SecondsLeft))),
            });
        }

        SourcesHeading.Text = Loc.GetString("beekeeping-debug-section-trays", ("count", data.Sources.Count));
        Sources.RemoveAllChildren();
        foreach (var source in data.Sources)
        {
            Sources.AddChild(SourceRow(data, source));
        }
    }

    private Control SourceRow(BeeHiveDebugData hive, BeeSourceDebugData source)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 8,
        };

        // The tray with its plant drawn over it, the way it looks on the floor.
        var picture = new Control { SetSize = new Vector2(32, 32) };
        foreach (var net in new[] { source.Tray, source.Plant })
        {
            if (net is not { } part || !_entityManager.TryGetEntity(part, out var uid) || !_entityManager.EntityExists(uid))
                continue;

            var sprite = new SpriteView { SetSize = new Vector2(32, 32), OverrideDirection = Direction.South };
            sprite.SetEntity(uid.Value);
            picture.AddChild(sprite);
        }
        row.AddChild(picture);

        var text = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical };
        text.AddChild(new Label
        {
            Text = Loc.GetString($"beekeeping-debug-state-{source.State.ToString().ToLowerInvariant()}"),
            FontColorOverride = BeeDebugOverlay.SourceColor(source.State),
        });
        var details = new Label
        {
            Text = Loc.GetString("beekeeping-debug-tray-line",
                ("tray", source.Tray.ToString()),
                ("distance", $"{Vector2.Distance(hive.Position, source.Position):0.#}"),
                ("visit", source.NextVisit <= 0f ? 0 : (int) source.NextVisit)),
        };
        details.StyleClasses.Add("LabelWeak");
        text.AddChild(details);
        row.AddChild(text);

        return row;
    }
}
