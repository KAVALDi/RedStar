/// <summary>
/// The apiary analyzer's window, laid out like the plant analyzer's: the scanned thing with its own lines and what
/// its traits add up to on the left; on the right the colony for a hive, or every trait explained for a queen or a
/// bee.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ApiaryAnalyzerWindow : FancyWindow
{
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    public ApiaryAnalyzerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Bees.AccentColor = Color.Gold;
        Nectar.AccentColor = Color.Orange;
        Combs.AccentColor = Color.Khaki;
        Health.AccentColor = Color.Crimson;
        NectarHelp.TooltipSupplier = _ =>
        {
            var tooltip = new Tooltip { MaxWidth = 600 };
            tooltip.SetMessage(_nectarHelp);
            return tooltip;
        };
        FeedingHelp.TooltipSupplier = _ =>
        {
            var tooltip = new Tooltip { MaxWidth = 400 };
            tooltip.SetMessage(_feedingHelp);
            return tooltip;
        };
    }

    private FormattedMessage _nectarHelp = new();
    private FormattedMessage _feedingHelp = new();

    /// <summary>
    /// Traits whose description was folded: the list is rebuilt on every refresh and keeps them folded.
    /// </summary>
    private readonly HashSet<string> _foldedTraits = new();

    public void UpdateState(ApiaryAnalyzerState state)
    {
        if (_entityManager.TryGetEntity(state.Target, out var target))
        {
            TargetSprite.SetEntity(target.Value);
            TargetName.Text = _entityManager.GetComponent<MetaDataComponent>(target.Value).EntityName;
        }

        var hive = state.Kind == ApiaryScanKind.Hive;
        HiveBox.Visible = hive;
        BeeBox.Visible = !hive;
        UpdateFeeding(state);

        // A hive lists its colony's traits on the left; a queen or a bee has its own lines there and every trait
        // explained on the right.
        Traits.Visible = hive;
        BeeInfo.Visible = !hive || state.HasQueen || state.Diet == BeehiveDiet.Meat;
        Traits.SetMessage(TraitList(state));

        UpdateStats(state.Totals);

        if (hive)
            UpdateHive(state);
        else
            UpdateBee(state);
    }

    private FormattedMessage TraitList(ApiaryAnalyzerState state)
    {
        var msg = new FormattedMessage();
        if (state.Kind == ApiaryScanKind.Hive && !state.HasQueen)
        {
            msg.AddText(Loc.GetString("apiary-analyzer-no-queen"));
            return msg;
        }

        if (state.Traits.Count == 0 && state.HiddenTraits == 0)
        {
            msg.AddText(Loc.GetString("beekeeping-traits-none"));
            return msg;
        }

        for (var i = 0; i < state.Traits.Count + state.HiddenTraits; i++)
        {
            if (i > 0)
                msg.AddText(", ");

            if (i >= state.Traits.Count)
            {
                msg.PushColor(Color.Gray);
                msg.AddText(Loc.GetString("beekeeping-trait-hidden"));
                msg.Pop();
                continue;
            }

            if (_proto.Resolve(state.Traits[i], out var trait))
            {
                msg.PushColor(trait.Color);
                msg.AddText(Loc.GetString(trait.Name));
                msg.Pop();
            }
            else
            {
                msg.AddText(state.Traits[i].Id);
            }
        }

        return msg;
    }

    /// <summary>
    /// Only what the traits change: a line the same as for plain bees says nothing.
    /// </summary>
    private void UpdateStats(BeeTraitTotals totals)
    {
        Stats.RemoveAllChildren();
        AddFactor("apiary-analyzer-stat-comb-rate", totals.CombRate, higherIsBetter: true);
        AddFactor("apiary-analyzer-stat-comb-cost", totals.CombCost, higherIsBetter: false);
        AddFactor("apiary-analyzer-stat-nectar", totals.NectarPerVisit, higherIsBetter: true);
        AddFactor("apiary-analyzer-stat-pollination", totals.PollinationChance, higherIsBetter: true);
        AddBonus("apiary-analyzer-stat-charges", totals.PollinatorCharges);
        AddFactor("apiary-analyzer-stat-bee-cost", totals.BeeCost, higherIsBetter: false);
        AddFactor("apiary-analyzer-stat-lay-rate", totals.LayRate, higherIsBetter: true);
        AddFactor("apiary-analyzer-stat-lifetime", totals.Lifetime, higherIsBetter: true);
        AddFactor("apiary-analyzer-stat-egg-wait", totals.EggWait, higherIsBetter: false);
        AddFactor("apiary-analyzer-stat-egg-life", totals.EggLife, higherIsBetter: true);
        AddFactor("apiary-analyzer-stat-egg-cooldown", totals.EggCooldown, higherIsBetter: false);
        AddBonus("apiary-analyzer-stat-scout-finds", totals.ScoutFinds);
        if (totals.PollinationMutation > 0f)
        {
            AddRow(Stats, "apiary-analyzer-stat-mutation",
                Loc.GetString("apiary-analyzer-units", ("amount", $"{totals.PollinationMutation:0.#}")), Color.Gold);
        }

        if (!IsPlain(totals.FlightPollination))
        {
            AddRow(Stats, "apiary-analyzer-stat-flight-pollination", $"{totals.FlightPollination * 100f:0}%",
                DeltaColor(totals.FlightPollination, true));
        }

        AddFactor("apiary-analyzer-stat-comb-yield", totals.CombYield, higherIsBetter: true);
        AddBonus("apiary-analyzer-stat-cap-wax", totals.CapWax);
        AddShift("apiary-analyzer-stat-cold", totals.ColdTolerance, "K");
        AddShift("apiary-analyzer-stat-heat", totals.HeatTolerance, "K");
        AddShift("apiary-analyzer-stat-pressure", totals.PressureTolerance, Loc.GetString("apiary-analyzer-kpa"));

        if (Stats.ChildCount == 0)
        {
            Stats.AddChild(WeakLabel("apiary-analyzer-stats-plain"));
            Stats.AddChild(new Control());
        }
    }

    private static bool IsPlain(float delta)
    {
        return MathF.Abs(delta) < 0.001f;
    }

    private void AddFactor(string name, float factor, bool higherIsBetter)
    {
        if (IsPlain(factor - 1f))
            return;

        AddRow(Stats, name, $"×{factor:0.##}", DeltaColor(factor - 1f, higherIsBetter));
    }

    /// <summary>
    /// How far the colony's traits widen (+) or narrow (−) the air it works in.
    /// </summary>
    private void AddShift(string name, float shift, string unit)
    {
        if (IsPlain(shift))
            return;

        var value = shift > 0f ? $"+{shift:0} {unit}" : $"{shift:0} {unit}";
        AddRow(Stats, name, value, DeltaColor(shift, true));
    }

    private void AddBonus(string name, int bonus)
    {
        if (bonus == 0)
            return;

        AddRow(Stats, name, bonus > 0 ? $"+{bonus}" : bonus.ToString(), DeltaColor(bonus, true));
    }

    private static Color DeltaColor(float delta, bool higherIsBetter)
    {
        if (IsPlain(delta))
            return Color.DimGray;

        return delta > 0f == higherIsBetter ? Color.LimeGreen : Color.Crimson;
    }

    private static void AddRow(GridContainer grid, string name, string value, Color? color = null)
    {
        grid.AddChild(new Label { Text = Loc.GetString(name), Margin = new Thickness(0, 0, 8, 0) });
        // Values sit against the right edge, so they line up whatever the labels' widths.
        var label = new Label
        {
            Text = value,
            FontColorOverride = color,
            HorizontalExpand = true,
            HorizontalAlignment = Control.HAlignment.Right,
        };
        if (color == null)
            label.StyleClasses.Add(StyleClass.LabelWeak);
        grid.AddChild(label);
    }

    private void UpdateHive(ApiaryAnalyzerState state)
    {
        InfoHeading.Text = Loc.GetString("apiary-analyzer-section-colony-traits");
        BeeInfo.RemoveAllChildren();
        if (state.HasQueen)
            AddQueenRows(state);
        // A meat colony lives on blood; the usual one does not need a line.
        if (state.Diet == BeehiveDiet.Meat)
            AddRow(BeeInfo, "apiary-analyzer-row-diet", Loc.GetString("apiary-analyzer-diet-meat"), Color.Crimson);
        Bees.Update(Loc.GetString("apiary-analyzer-bees"),
            $"{state.Bees + state.OutBees} / {state.MaxBees}",
            progress: state.MaxBees > 0 ? (float) (state.Bees + state.OutBees) / state.MaxBees : 0f);
        if (state.Diet == BeehiveDiet.Meat)
        {
            // A meat hive shows how much meat it would give, and the info mark says which kinds can fall.
            Nectar.Update(Loc.GetString("apiary-analyzer-meat"),
                $"{state.MeatDrops} / {state.MeatMax}",
                progress: state.MeatMax > 0 ? (float) state.MeatDrops / state.MeatMax : 0f);
            _nectarHelp = MeatHelp(state);
        }
        else
        {
            Nectar.Update(Loc.GetString("apiary-analyzer-nectar"),
                $"{state.Nectar:0.#} / {state.MaxNectar:0.#}",
                progress: state.MaxNectar > 0f ? state.Nectar / state.MaxNectar : 0f);
            // Most of the time the stock stays low because it is spent at once: the info mark says what it goes into.
            _nectarHelp = FormattedMessage.FromMarkupPermissive(
                Loc.GetString($"apiary-analyzer-nectar-{state.NectarUse.ToString().ToLowerInvariant()}"));
        }
        Combs.Update(Loc.GetString("apiary-analyzer-combs"),
            $"{state.Combs} / {state.MaxCombs}",
            progress: state.MaxCombs > 0 ? (float) state.Combs / state.MaxCombs : 0f);
        Health.Update(Loc.GetString("apiary-analyzer-health"),
            $"{state.Health:0} / {state.MaxHealth:0}",
            progress: state.MaxHealth > 0f ? state.Health / state.MaxHealth : 0f);

        BeesHome.Text = state.Bees.ToString();
        NewBee.Text = Loc.GetString(state.BroodGoing ? "apiary-analyzer-brood-going" : "apiary-analyzer-brood-stopped");
        Queen.Text = Loc.GetString(state.HasQueen ? "apiary-analyzer-yes" : "apiary-analyzer-no");
        Egg.Text = Loc.GetString(state.HasEgg ? "apiary-analyzer-yes" : "apiary-analyzer-no");
        Egg.FontColorOverride = state.SwarmComing ? Color.Orange : null;
        Foraging.Text = state.Foraging.ToString();

        // A wild hive builds its combs right inside, with no frames; a meat one lists what it holds instead.
        FramesPanel.Visible = !state.Wild;
        ChemicalsPanel.Visible = state.Wild && state.Diet == BeehiveDiet.Meat;
        Chemicals.ShowEmptyMessage();
        foreach (var chemical in state.Chemicals)
        {
            Chemicals.AddReagent(new ReagentId(chemical.Reagent, null), FixedPoint2.New(chemical.Amount));
        }
        FramesHeading.Text = Loc.GetString("apiary-analyzer-section-frames", ("count", state.Frames.Count));
        Frames.RemoveAllChildren();
        if (state.Frames.Count == 0)
            Frames.AddChild(WeakLabel("apiary-analyzer-frames-none"));
        foreach (var frame in state.Frames)
        {
            // One row per frame: its picture, which follows the combs as it fills and gets capped, and the count.
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
                ToolTip = frame.Prototype is { } proto && _proto.TryIndex(proto, out var entity) ? entity.Name : null,
            };
            var picture = new SpriteView { SetSize = new Vector2(32, 32), OverrideDirection = Direction.South };
            if (_entityManager.TryGetEntity(frame.Frame, out var frameUid) && _entityManager.EntityExists(frameUid))
                picture.SetEntity(frameUid.Value);
            row.AddChild(picture);
            row.AddChild(new Label
            {
                Text = Loc.GetString("apiary-analyzer-frame-combs", ("combs", frame.Combs), ("max", frame.MaxCombs)),
                VerticalAlignment = VAlignment.Center,
                StyleClasses = { StyleClass.LabelWeak },
            });
            Frames.AddChild(row);
        }

        // A meat hive has no scout and remembers only whom it bit lately.
        var meat = state.Diet == BeehiveDiet.Meat;
        TraysHeading.Text = Loc.GetString(meat ? "apiary-analyzer-section-targets" : "apiary-analyzer-section-trays",
            ("count", state.Trays.Count));
        Trays.RemoveAllChildren();
        if (state.Trays.Count == 0)
            Trays.AddChild(WeakLabel(meat ? "apiary-analyzer-targets-none" : "apiary-analyzer-trays-none"));
        // Longest plant names first, so the list narrows downwards.
        // Rows alternate between two backgrounds, like the harvest chemicals of the plant analyzer.
        var stripe = 0;
        foreach (var (tray, name) in state.Trays
                     .Select(tray => (tray, TrayName(tray)))
                     .OrderByDescending(pair => pair.Item2.Length))
        {
            Trays.AddChild(new PanelContainer
            {
                StyleClasses = { stripe++ % 2 == 0 ? StyleClass.Panel : StyleClass.PanelDark },
                Children = { TrayRow(tray, name) },
            });
        }
    }

    /// <summary>
    /// The info mark of the meat bar: how the meat comes and which kinds can fall, with their chances.
    /// </summary>
    private FormattedMessage MeatHelp(ApiaryAnalyzerState state)
    {
        var msg = FormattedMessage.FromMarkupPermissive(Loc.GetString("apiary-analyzer-meat-help",
            ("base", state.MeatBase), ("per", state.MeatPerDrop), ("max", state.MeatMax)));
        foreach (var chance in state.MeatChances)
        {
            if (!_proto.TryIndex(chance.Meat, out var meat))
                continue;

            var names = string.Join(" + ", meat.Entities.Select(id => _proto.TryIndex(id, out var entity) ? entity.Name : id.Id));
            msg.PushNewline();
            msg.AddText(Loc.GetString("apiary-analyzer-meat-chance", ("name", names), ("percent", $"{chance.Percent:0}")));
        }

        return msg;
    }

    private string TrayName(ApiaryTrayData tray)
    {
        if (tray.Creature)
        {
            if (tray.CreatureName != null)
                return Loc.GetString(tray.CreatureName);

            return tray.CreaturePrototype is { } kind && _proto.TryIndex(kind, out var animal) ? animal.Name : string.Empty;
        }

        return tray.PlantPrototype is { } plant && _proto.TryIndex(plant, out var entity)
            ? entity.Name
            : Loc.GetString("apiary-analyzer-tray-empty");
    }

    private Control TrayRow(ApiaryTrayData tray, string name)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 8,
            Margin = new Thickness(4, 2),
        };

        // A bar on the left: green for a ripe plant, yellow while it grows, red for nothing the workers can reach.
        var (barColor, barTip) = tray.State switch
        {
            ApiaryTrayState.Ripe => (Color.FromHex("#98C379"), tray.Creature ? "apiary-analyzer-creature-ripe" : "apiary-analyzer-tray-ripe"),
            ApiaryTrayState.Growing => (Color.FromHex("#E5C07B"), "apiary-analyzer-tray-growing"),
            _ => (Color.FromHex("#E06C75"), tray.Creature ? "apiary-analyzer-creature-blind" : "apiary-analyzer-tray-blind"),
        };
        row.AddChild(new PanelContainer
        {
            PanelOverride = new StyleBoxFlat { BackgroundColor = barColor },
            SetWidth = 3,
            VerticalExpand = true,
            ToolTip = Loc.GetString(barTip),
            MouseFilter = MouseFilterMode.Stop,
        });

        // The tray with its plant drawn over it, the way it looks on the floor. A creature is drawn as a plain picture of
        // its kind, not as the creature itself.
        var picture = new Control { SetSize = new Vector2(32, 32) };
        if (tray.Creature)
        {
            var still = new EntityPrototypeView { SetSize = new Vector2(32, 32), OverrideDirection = Direction.South };
            still.SetPrototype(tray.CreaturePrototype);
            picture.AddChild(still);
        }

        foreach (var net in tray.Creature ? Array.Empty<NetEntity?>() : new[] { tray.Tray, tray.Plant })
        {
            if (net is not { } part || !_entityManager.TryGetEntity(part, out var uid) || !_entityManager.EntityExists(uid))
                continue;

            var sprite = new SpriteView { SetSize = new Vector2(32, 32), OverrideDirection = Direction.South };
            sprite.SetEntity(uid.Value);
            picture.AddChild(sprite);
        }
        row.AddChild(picture);

        row.AddChild(new Label
        {
            Text = name,
            VerticalAlignment = VAlignment.Center,
        });

        return row;
    }

    private void UpdateBee(ApiaryAnalyzerState state)
    {
        TraitDetails.RemoveAllChildren();
        if (state.Traits.Count == 0 && state.HiddenTraits == 0)
            TraitDetails.AddChild(WeakLabel("beekeeping-traits-none"));
        for (var i = 0; i < state.HiddenTraits; i++)
        {
            TraitDetails.AddChild(TraitEntry($"hidden-{i}", Loc.GetString("beekeeping-trait-hidden"), Color.Gray,
                Loc.GetString("beekeeping-trait-hidden-desc"), TraitDetails.ChildCount));
        }

        foreach (var id in state.Traits)
        {
            TraitDetails.AddChild(_proto.Resolve(id, out var trait)
                ? TraitEntry(id, Loc.GetString(trait.Name), trait.Color, Loc.GetString(trait.Description),
                    TraitDetails.ChildCount)
                : TraitEntry(id, id.Id, Color.White, string.Empty, TraitDetails.ChildCount));
        }

        BeeInfo.RemoveAllChildren();
        switch (state.Kind)
        {
            case ApiaryScanKind.Queen:
                InfoHeading.Text = Loc.GetString("apiary-analyzer-section-queen");
                AddQueenRows(state, payload: false);
                break;
            case ApiaryScanKind.Scout:
                InfoHeading.Text = Loc.GetString("apiary-analyzer-section-scout");
                AddRow(BeeInfo, "apiary-analyzer-row-hive",
                    Loc.GetString(state.HiveKnown ? "apiary-analyzer-hive-known" : "apiary-analyzer-hive-lost"),
                    state.HiveKnown ? null : Color.Crimson);
                AddRow(BeeInfo, "apiary-analyzer-row-memory",
                    Loc.GetString("apiary-analyzer-of", ("value", state.Memory), ("max", state.MemoryLimit)));
                break;
            default:
                InfoHeading.Text = Loc.GetString("apiary-analyzer-section-pollinator");
                AddRow(BeeInfo, "apiary-analyzer-row-charges", state.Charges.ToString());
                break;
        }
    }

    /// <summary>
    /// For a scanned queen: what each reagent does when injected, with how far along she is.
    /// </summary>
    private void UpdateFeeding(ApiaryAnalyzerState state)
    {
        FeedingPanel.Visible = state.Kind == ApiaryScanKind.Queen && state.Feeding != null;
        if (state.Feeding is not { } feeding)
            return;

        var mutagen = ReagentName(feeding.Mutagen);
        var jelly = ReagentName(feeding.Jelly);

        Feeding.RemoveAllChildren();
        AddFeedingRow(Loc.GetString("apiary-analyzer-feed-mutagen"), Loc.GetString("apiary-analyzer-feed-progress",
            ("progress", $"{feeding.MutagenProgress:0.#}"), ("per", $"{feeding.MutagenPerRoll:0.#}")));
        AddFeedingRow(Loc.GetString("apiary-analyzer-feed-jelly"), state.Slots >= feeding.MaxSlots
            ? Loc.GetString("apiary-analyzer-feed-jelly-full")
            : Loc.GetString("apiary-analyzer-feed-progress",
                ("progress", $"{feeding.JellyProgress:0.#}"), ("per", $"{feeding.JellyPerSlot:0.#}")));
        AddFeedingRow(Loc.GetString("apiary-analyzer-feed-other"), state.Totals.Sting
            ? Loc.GetString("apiary-analyzer-feed-progress",
                ("progress", $"{state.Payload:0.#}"), ("per", $"{state.PayloadCap:0.#}"))
            : Loc.GetString("apiary-analyzer-feed-other-no-sting"));

        var help = new List<string>
        {
            Loc.GetString("apiary-analyzer-feed-help-how"),
            Loc.GetString("apiary-analyzer-feed-help-mutagen", ("reagent", mutagen), ("color", ReagentColor(feeding.Mutagen)),
                ("per", $"{feeding.MutagenPerRoll:0.#}")),
            Loc.GetString("apiary-analyzer-feed-help-jelly", ("reagent", jelly), ("color", Color.White.ToHex()),
                ("per", $"{feeding.JellyPerSlot:0.#}"), ("max", feeding.MaxSlots)),
            Loc.GetString(state.Totals.Sting ? "apiary-analyzer-feed-help-sting" : "apiary-analyzer-feed-help-no-sting",
                ("cap", $"{state.PayloadCap:0.#}")),
        };
        _feedingHelp = FormattedMessage.FromMarkupOrThrow(string.Join("\n", help));
    }

    private void AddFeedingRow(string name, string value)
    {
        Feeding.AddChild(new Label { Text = name, Margin = new Thickness(0, 0, 8, 0) });
        Feeding.AddChild(new Label
        {
            Text = value,
            HorizontalExpand = true,
            HorizontalAlignment = Control.HAlignment.Right,
            StyleClasses = { StyleClass.LabelWeak },
        });
    }

    /// <summary>
    /// The reagent's own colour, so its name in the help looks like it does in a beaker.
    /// </summary>
    private string ReagentColor(ProtoId<ReagentPrototype> reagent)
    {
        return (_proto.TryIndex(reagent, out var proto) ? proto.SubstanceColor : Color.White).ToHex();
    }

    private string ReagentName(ProtoId<ReagentPrototype> reagent)
    {
        return _proto.TryIndex(reagent, out var proto) ? proto.LocalizedName : reagent.Id;
    }

    /// <param name="payload">Off for a queen in hand: her reagents are listed with the syringe rows.</param>
    private void AddQueenRows(ApiaryAnalyzerState state, bool payload = true)
    {
        // Coloured like the stats: grey when nothing special, red for wear on the queen.
        AddRow(BeeInfo, "apiary-analyzer-row-slots",
            Loc.GetString("apiary-analyzer-of", ("value", state.UsedSlots), ("max", state.Slots)), Color.DimGray);
        AddRow(BeeInfo, "apiary-analyzer-row-instability", state.Instability.ToString(),
            DeltaColor(state.Instability, false));
        if (payload)
        {
            AddRow(BeeInfo, "apiary-analyzer-row-payload",
                Loc.GetString("apiary-analyzer-of", ("value", $"{state.Payload:0.#}"), ("max", $"{state.PayloadCap:0.#}")),
                Color.DimGray);
        }
    }

    /// <summary>
    /// A trait as a row like the known trays: alternating background, a bar in the trait's colour, and its name that
    /// folds and unfolds what it does when clicked.
    /// </summary>
    private Control TraitEntry(string key, string name, Color color, string description, int index)
    {
        var heading = new CollapsibleHeading(name)
        {
            ChevronVisible = false,
            ToolTip = Loc.GetString("apiary-analyzer-trait-fold"),
        };
        heading.Label.FontColorOverride = color;
        var text = new RichTextLabel();
        text.SetMessage(FormattedMessage.FromUnformatted(description));
        var entry = new Collapsible(heading, new CollapsibleBody { Children = { text } })
        {
            BodyVisible = !_foldedTraits.Contains(key),
            HorizontalExpand = true,
        };

        heading.OnToggled += args =>
        {
            if (args.Pressed)
                _foldedTraits.Remove(key);
            else
                _foldedTraits.Add(key);
        };

        return new PanelContainer
        {
            StyleClasses = { index % 2 == 0 ? StyleClass.Panel : StyleClass.PanelDark },
            Children =
            {
                new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    SeparationOverride = 8,
                    Margin = new Thickness(4, 2),
                    Children =
                    {
                        new PanelContainer
                        {
                            PanelOverride = new StyleBoxFlat { BackgroundColor = color },
                            SetWidth = 3,
                            VerticalExpand = true,
                        },
                        entry,
                    },
                },
            },
        };
    }

    private static Label WeakLabel(string loc)
    {
        return new Label { Text = Loc.GetString(loc), StyleClasses = { StyleClass.LabelWeak } };
    }
}
